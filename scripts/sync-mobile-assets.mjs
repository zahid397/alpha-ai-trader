// Copies the web game (public/game) into the Flutter app's bundled assets
// (mobile/assets/game) and rewrites the asset list in mobile/pubspec.yaml,
// so the app ships the exact same build and runs it fully offline.
//
//   npm run mobile:assets        (run after changing the game)
//
// Flutter only bundles the folders listed in pubspec.yaml and does not
// recurse into sub-folders, so every folder is listed.
import { cpSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const source = join(root, 'public', 'game');
const target = join(root, 'mobile', 'assets', 'game');
const pubspec = join(root, 'mobile', 'pubspec.yaml');
const START = '    # game-assets:start (generated by scripts/sync-mobile-assets.mjs)';
const END = '    # game-assets:end';

export function folders(dir) {
  const out = [];
  const walk = (d) => {
    const entries = readdirSync(d, { withFileTypes: true });
    if (entries.some((e) => e.isFile())) out.push(d);
    for (const e of entries) if (e.isDirectory()) walk(join(d, e.name));
  };
  walk(dir);
  return out.sort();
}

export function assetBlock(dir = target) {
  const lines = folders(dir).map((d) => `    - ${relative(join(root, 'mobile'), d).split(sep).join('/')}/`);
  return [START, ...lines, END].join('\n');
}

function sync() {
  rmSync(target, { recursive: true, force: true });
  cpSync(source, target, { recursive: true });

  const yaml = readFileSync(pubspec, 'utf8');
  const block = assetBlock();
  const pattern = new RegExp(`${escape(START)}[\\s\\S]*?${escape(END)}`);
  if (!pattern.test(yaml)) throw new Error('mobile/pubspec.yaml is missing the game-assets markers');
  writeFileSync(pubspec, yaml.replace(pattern, block));

  let files = 0;
  let bytes = 0;
  for (const d of folders(target)) {
    for (const f of readdirSync(d)) {
      const s = statSync(join(d, f));
      if (s.isFile()) {
        files++;
        bytes += s.size;
      }
    }
  }
  console.log(`Synced ${files} files (${(bytes / 1024 / 1024).toFixed(2)} MB) -> mobile/assets/game`);
  console.log(block);
}

function escape(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) sync();
